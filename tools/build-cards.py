#!/usr/bin/env python3
"""Build game assets from the Void Tarot source project (read-only).

  python3 tools/build-cards.py [path-to-void-tarot]

Writes assets/cards/NN.jpg (large), assets/thumbs/NN.jpg (small),
assets/back.jpg, assets/back-thumb.jpg and src/cards.js.
Uses macOS `sips` for resizing. Source art is never modified.
"""
import json, os, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/mydev/void-tarot')
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LARGE_H, LARGE_Q = 800, 62
THUMB_H, THUMB_Q = 260, 68

ELEMENT = {'wands': 'fire', 'cups': 'water', 'swords': 'air', 'pentacles': 'earth', 'major': 'void'}
ROMAN = ['0', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII', 'XIII',
         'XIV', 'XV', 'XVI', 'XVII', 'XVIII', 'XIX', 'XX', 'XXI']
COURT = {11: 'page', 12: 'knight', 13: 'queen', 14: 'king'}


def sips(src, dst, h, q):
    subprocess.run(['sips', '-s', 'format', 'jpeg', '-s', 'formatOptions', str(q),
                    '--resampleHeight', str(h), src, '--out', dst],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def title_case(t):
    small = {'of', 'the'}
    words = t.lower().split()
    return ' '.join(w if (w in small and i > 0) else w.capitalize() for i, w in enumerate(words))


def main():
    manifest = json.load(open(os.path.join(SRC, 'deck/selected/manifest.json')))['cards']
    meanings = json.load(open(os.path.join(SRC, 'VoidTarot/Resources/Data/TarotMeaning.json')))['cards']
    assert len(manifest) == 78 and len(meanings) == 78
    for d in ('assets/cards', 'assets/thumbs', 'src'):
        os.makedirs(os.path.join(ROOT, d), exist_ok=True)

    jobs, cards = [], []
    for m, t in zip(sorted(manifest, key=lambda c: c['index']), meanings):
        i = m['index']
        assert m['title'] == t['title'], (m['title'], t['title'])
        src = os.path.join(SRC, m['output'])
        jobs.append((src, os.path.join(ROOT, 'assets/cards/%02d.jpg' % i), LARGE_H, LARGE_Q))
        jobs.append((src, os.path.join(ROOT, 'assets/thumbs/%02d.jpg' % i), THUMB_H, THUMB_Q))
        suit, num = m['suit'], t['number']
        if suit == 'major':
            kind, rank = 'trump', ROMAN[num]
        elif num >= 11:
            kind, rank = 'court', COURT[num]
        else:
            kind, rank = 'pip', str(num)
        cards.append({
            'id': i, 'name': title_case(m['title']), 'suit': suit, 'el': ELEMENT[suit],
            'kind': kind, 'num': num, 'rank': rank,
            'kw': t['upright']['keywords'][:3], 'rkw': t['reversed']['keywords'][:3],
            'meaning': t['meaning'],
        })
    back = os.path.join(SRC, 'deck/card-back/card-back-v1.png')
    jobs.append((back, os.path.join(ROOT, 'assets/back.jpg'), LARGE_H, LARGE_Q))
    jobs.append((back, os.path.join(ROOT, 'assets/back-thumb.jpg'), THUMB_H, THUMB_Q))

    with ThreadPoolExecutor(8) as ex:
        list(ex.map(lambda j: sips(*j), jobs))

    with open(os.path.join(ROOT, 'src/cards.js'), 'w') as f:
        f.write('// Generated by tools/build-cards.py. Do not edit by hand.\n')
        f.write('var VT_CARDS = [\n')
        for c in cards:
            f.write('  ' + json.dumps(c, ensure_ascii=False) + ',\n')
        f.write('];\nif (typeof module !== "undefined") module.exports = VT_CARDS;\n')

    total = 0
    for d in ('assets/cards', 'assets/thumbs', 'assets'):
        p = os.path.join(ROOT, d)
        total += sum(os.path.getsize(os.path.join(p, x)) for x in os.listdir(p) if x.endswith('.jpg'))
    print('cards: %d, assets: %.1f MB' % (len(cards), total / 1e6))


if __name__ == '__main__':
    main()
