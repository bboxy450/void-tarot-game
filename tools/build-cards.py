#!/usr/bin/env python3
"""Regenerate src/cards.js and assets/cards/ from the Void Tarot project.
Usage: python3 tools/build-cards.py [path-to-void-tarot]   (default ~/mydev/void-tarot)"""
import json, os, subprocess, sys

SRC = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/mydev/void-tarot")
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "assets", "cards")
os.makedirs(OUT, exist_ok=True)

manifest = json.load(open(os.path.join(SRC, "deck/selected/manifest.json")))["cards"]
meanings = json.load(open(os.path.join(SRC, "VoidTarot/Resources/Data/TarotMeaning.json")))["cards"]
assert len(manifest) == 78 and len(meanings) == 78

def shrink(src, dst):
    if not os.path.exists(dst):
        subprocess.run(["sips", "-s", "format", "jpeg", "-s", "formatOptions", "70",
                        "--resampleHeight", "480", src, "--out", dst],
                       check=True, stdout=subprocess.DEVNULL)

cards = []
for m, t in zip(sorted(manifest, key=lambda c: c["index"]), meanings):
    name = os.path.splitext(os.path.basename(m["output"]))[0]
    assert name.endswith(t["slug"]), (t["slug"], name)
    shrink(os.path.join(SRC, m["output"]), os.path.join(OUT, name + ".jpg"))
    cards.append({
        "i": m["index"],
        "title": m["title"].title().replace(" Of ", " of "),
        "suit": m["suit"],
        "rank": t.get("rank"),
        "n": t.get("number"),
        "up": t["upright"]["keywords"][:3],
        "meaning": t["meaning"],
        "img": "assets/cards/" + name + ".jpg",
    })
shrink(os.path.join(SRC, "deck/card-back/card-back-v1.png"), os.path.join(OUT, "back.jpg"))

with open(os.path.join(HERE, "src", "cards.js"), "w") as f:
    f.write("// Generated by tools/build-cards.py from the Void Tarot project. Do not edit.\n")
    f.write("var CARDS = " + json.dumps(cards, indent=0, ensure_ascii=False) + ";\n")
    f.write("if (typeof module !== 'undefined') module.exports = CARDS;\n")
print(len(cards), "cards")
