// Downsizes the Void Tarot card art into public/cards and writes src/game/cardData.ts.
// Source (read-only): ~/mydev/void-tarot. Usage: node scripts/prepare-cards.mjs [sourceDir]
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, basename } from 'node:path';

const src = process.argv[2] ?? join(homedir(), 'mydev/void-tarot');
const root = new URL('..', import.meta.url).pathname;
const out = join(root, 'public/cards');
mkdirSync(out, { recursive: true });

const manifest = JSON.parse(readFileSync(join(src, 'deck/selected/manifest.json'), 'utf8'));
const meanings = JSON.parse(readFileSync(join(src, 'VoidTarot/Resources/Data/TarotMeaning.json'), 'utf8'));

function shrink(from, to, height) {
  if (existsSync(to)) return;
  execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '78', '--resampleHeight', String(height), from, '--out', to], { stdio: 'ignore' });
}

const cards = manifest.cards
  .slice()
  .sort((a, b) => a.index - b.index)
  .map((c) => {
    const m = meanings.cards[c.index];
    const file = basename(c.output).replace(/\.png$/, '.jpg');
    shrink(join(src, c.output), join(out, file), 420);
    const title = c.title.replace(/\b([A-Z])([A-Z]*)\b/g, (_, a, b) => a + b.toLowerCase()).replace(/\bOf\b/g, 'of');
    return {
      index: c.index,
      title,
      suit: c.suit,
      image: `cards/${file}`,
      meaning: m.meaning,
      keywords: m.upright?.keywords ?? [],
    };
  });
shrink(join(src, 'deck/card-back/card-back-v1.png'), join(out, 'back.jpg'), 420);

const ts = `// Generated by scripts/prepare-cards.mjs. Do not edit by hand.
export type Suit = 'major' | 'wands' | 'cups' | 'swords' | 'pentacles';
export interface CardInfo { index: number; title: string; suit: Suit; image: string; meaning: string; keywords: string[] }
export const CARDS: CardInfo[] = ${JSON.stringify(cards, null, 1)};
export const CARD_BACK = 'cards/back.jpg';
`;
writeFileSync(join(root, 'src/game/cardData.ts'), ts);
console.log(`wrote ${cards.length} cards`);
